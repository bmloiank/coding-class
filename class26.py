# 교체를 4번(길이의 절반) 반복적으로 할겁니다.


last_index = len(lst)-1

for i in range(len(lst)//2):
    # 교체할 앞 데이터
    # 반복해서 교체를 하고싶다
    front = lst[i]
    back = lst[last_index-i]
    lst[i] = back
    lst[last_index-i] = front
    
